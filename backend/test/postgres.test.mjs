test('PostgreSQL migrations, cross-connection quota races, rollback, history and cancellation', { skip: !process.env.TEST_DATABASE_URL }, async (t) => {
  const admin = new PostgresDatabase(process.env.TEST_DATABASE_URL);
  const schema = 'test_' + randomUUID().replaceAll('-', '');
  await admin.query(`CREATE SCHEMA ${schema}`);
  const url = new URL(process.env.TEST_DATABASE_URL); url.searchParams.set('options', '-csearch_path=' + schema);
  const db1 = new PostgresDatabase(url.href), db2 = new PostgresDatabase(url.href);
  t.after(async () => { await db1.close(); await db2.close(); await admin.query(`DROP SCHEMA ${schema} CASCADE`); await admin.close(); });
  await Promise.all([db1.migrate(), db2.migrate()]);
  const one = new PostgresStore(db1), two = new PostgresStore(db2);
  const directory = mkdtempSync(join(tmpdir(), 'flagship-migration-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const source = new Store(join(directory, 'source.sqlite'));
  const legacy = source.createUser('legacy', 'preserved-password-hash', 'preserved-recovery-hash');
  source.createSession(legacy.id, 'legacy-session', 'legacy-csrf', 3600);
  source.db.prepare("INSERT INTO operations(user_id,id,concept_id,fingerprint,kind,state,result,created) VALUES(?,?,?,?,?,?,?,?)").run(legacy.id, 'legacy-receipt', 'polity/state', 'legacy-fingerprint', 'chat', 'completed', '{}', source.now());
  source.ensure(legacy.id, 'polity/state'); source.addMessage(legacy.id, 'polity/state', 'student', 'Preserve ₹100 and தமிழ்');
  const backup = join(directory, 'consistent.sqlite'); await source.backup(backup); source.close();
  const old = new DatabaseSync(backup); old.exec('ALTER TABLE operations DROP COLUMN generation; ALTER TABLE operations DROP COLUMN lease_owner; ALTER TABLE operations DROP COLUMN cancelled_at; PRAGMA user_version=4'); old.close();
  const imported = await migrateSqlite(backup, url.href); assert.equal(imported.imported.users, 1);
  assert.equal((await one.operation(legacy.id, 'legacy-receipt')).generation, 1);
  assert.equal((await one.userByName('legacy')).password_hash, 'preserved-password-hash');
  assert.equal((await one.state(legacy.id, 'polity/state')).messages[0].text, 'Preserve ₹100 and தமிழ்');
  assert.equal(await one.session('legacy-session'), undefined);
  await assert.rejects(migrateSqlite(backup, url.href), /Target must be empty/);
  const user = await one.createUser('learner', 'hash', 'recovery');
  const activities = new ActivityService(one), otherActivities = new ActivityService(two);
  await activities.save(user.id, 'roadmap', { themeId: 1, completed: true, revision: 0 });
  assert.equal((await otherActivities.snapshot(user.id)).roadmap[0].completed, true);
  await assert.rejects(otherActivities.save(user.id, 'roadmap', { themeId: 1, completed: false, revision: 0 }), /another device/);
  await one.createSession(user.id, 'session', 'csrf', 3600);
  const config = readConfig({ GLOBAL_DAILY_CALLS: '1' });
  const request = { userId: user.id, ip: 'test', conceptId: 'polity/state', fingerprint: 'test', kind: 'chat', revision: 0, tokens: 100, config, promptVersion: 'p1', lessonVersion: 'l1' };
  const results = await Promise.allSettled([one.reserve({ ...request, id: 'a' }), two.reserve({ ...request, id: 'b' })]);
  assert.equal(results.filter((r) => r.status === 'fulfilled').length, 1);
  const reservation = results.find((r) => r.status === 'fulfilled').value;
  await assert.rejects(one.finish(reservation, 'session', async () => { await one.ensure(user.id, request.conceptId); throw new Error('rollback'); }), /rollback/);
  assert.equal(await two.row(user.id, request.conceptId), undefined);
  await one.finish(reservation, 'session', async () => {
    await one.ensure(user.id, request.conceptId);
    for (let i = 0; i < 65; i++) await one.addMessage(user.id, request.conceptId, 'student', 'message ' + i);
    return { saved: true };
  }, { input_tokens: 10, output_tokens: 20 });
  assert.equal((await two.operation(user.id, reservation.id)).lesson_version, 'l1');
  assert.equal((await two.export(user.id)).progress[0].messages.length, 65);
  const latest = await two.state(user.id, request.conceptId);
  assert.equal(latest.hasOlderMessages, true);
  assert.equal((await two.olderMessages(user.id, request.conceptId, latest.messages[0].id)).length, 5);
  const recordedAt = Date.now() - 1000;
  await one.transaction(async () => {
    for (let i = 0; i < 52; i++) await one.recordAssessment(user.id, request.conceptId, { id: randomUUID(), recordedAt, answers: [], questions: [{ question: 'History question', expected: 'private' }] });
  });
  const firstHistory = await two.assessmentHistory(user.id, request.conceptId, recordedAt + 1, 50), lastCheck = firstHistory.at(-1);
  const secondHistory = await two.assessmentHistory(user.id, request.conceptId, lastCheck.recorded, 50, lastCheck.id);
  assert.equal(firstHistory.length, 50); assert.equal(secondHistory.length, 2);
  assert.equal(new Set([...firstHistory, ...secondHistory].map((check) => check.id)).size, 52);
  const replay = await two.reserve({ ...request, id: reservation.id }); assert.deepEqual(replay.replay, { saved: true });
  const next = await one.reserve({ ...request, id: 'c', config: { ...config, globalDailyCalls: 10 } });
  await two.signOut('session');
  await assert.rejects(one.finish(next, 'session', async () => ({ saved: true })), /Sign in again/);
  assert.equal((await one.operation(user.id, 'c')).state, 'cancelled');
  await one.createSession(user.id, 'new-session', 'new-csrf', 3600);
  const leased = await one.reserve({ ...request, id: 'd', config: { ...config, globalDailyCalls: 10 } });
  const originalNow = one.now; one.now = () => originalNow() + 180001;
  await one.cleanup();
  assert.equal((await two.operation(user.id, 'd')).state, 'indeterminate');
  await assert.rejects(one.finish(leased, 'new-session', async () => ({ invalid: true })), /Sign in again/);
  const recoveries = await Promise.allSettled([
    one.recover(user.id, 'new-hash-one', 'new-recovery-one', 'recovery'),
    two.recover(user.id, 'new-hash-two', 'new-recovery-two', 'recovery'),
  ]);
  assert.equal(recoveries.filter((r) => r.status === 'fulfilled').length, 1);
  await assert.rejects(two.createSession(user.id, 'stale-login', 'csrf', 3600, 'hash'), /credentials changed/);
  assert.equal(await two.session('stale-login'), undefined);
  await assert.rejects(two.deleteUser(user.id, 'new-session', 'hash'), /account changed/);
  assert(await two.userByName('learner'));
});

test('encrypted PostgreSQL backup restores learner data atomically with the retained key', { skip: !process.env.TEST_DATABASE_URL || !process.env.PG_DUMP_BIN || !process.env.PG_RESTORE_BIN }, async (t) => {
  const admin = new PostgresDatabase(process.env.TEST_DATABASE_URL), name = 'restore_' + randomUUID().replaceAll('-', '');
  await admin.query(`CREATE DATABASE ${name}`);
  const sourceUrl = new URL(process.env.TEST_DATABASE_URL), restoreUrl = new URL(process.env.TEST_DATABASE_URL);
  const sourceName = name + '_source'; await admin.query(`CREATE DATABASE ${sourceName}`);
  sourceUrl.pathname = '/' + sourceName; restoreUrl.pathname = '/' + name;
  const db = new PostgresDatabase(sourceUrl.href), restored = new PostgresDatabase(restoreUrl.href);
  const directory = mkdtempSync(join(tmpdir(), 'flagship-restore-'));
  t.after(async () => { await db.close(); await restored.close(); await admin.query(`DROP DATABASE ${name}`); await admin.query(`DROP DATABASE ${sourceName}`); await admin.close(); rmSync(directory, { recursive: true, force: true }); });
  await db.migrate(); const store = new PostgresStore(db);
  const learner = await store.createUser('restore_learner', 'preserved-hash', 'preserved-recovery');
  await store.ensure(learner.id, 'polity/state'); await store.addMessage(learner.id, 'polity/state', 'student', 'Restore ₹100 · தமிழ்');
  const key = randomBytes(32).toString('base64'), path = join(directory, 'backup.dump.enc'), started = Date.now();
  const result = await backupPostgres(sourceUrl.href, path, key, process.env.PG_DUMP_BIN); assert(result.bytes > 28);
  await assert.rejects(backupPostgres(sourceUrl.href, path, key, process.env.PG_DUMP_BIN), /EEXIST/);
  await assert.rejects(restorePostgres(restoreUrl.href, path, randomBytes(32).toString('base64'), process.env.PG_RESTORE_BIN));
  await restorePostgres(restoreUrl.href, path, key, process.env.PG_RESTORE_BIN);
  const recovered = new PostgresStore(restored);
  assert.equal((await recovered.userByName('restore_learner')).password_hash, 'preserved-hash');
  assert.equal((await recovered.state(learner.id, 'polity/state')).messages[0].text, 'Restore ₹100 · தமிழ்');
  assert(Date.now() - started < 60000, 'Small-data restore rehearsal exceeded one minute');
});
