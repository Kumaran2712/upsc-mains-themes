import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fixture, client, goodPassword } from './helpers.mjs';
import { dayKey } from '../store.mjs';
const daily = JSON.parse(readFileSync(new URL('../../src/data/daily.json', import.meta.url)));
const prelims = JSON.parse(readFileSync(new URL('../../data/prelims.json', import.meta.url)));

test('account activities enforce ownership, revisions, immutable scored attempts and repeat-safe guest imports', async (t) => {
  const f = await fixture(); t.after(() => f.close());
  const alice = client(f.base), bob = client(f.base);
  await alice.signup('activity_alice'); await bob.signup('activity_bob');
  assert.equal((await alice.json('/activity/roadmap', { themeId: 1, completed: true, revision: 0 })).status, 200);
  assert.equal((await alice.json('/activity/roadmap', { themeId: 1, completed: false, revision: 0 })).status, 409);
  assert.equal((await bob.json('/activity')).body.roadmap.length, 0);
  const day = dayKey(), offset = Math.floor((Date.parse(day) - Date.parse(daily.epoch)) / 86400000), ids = daily.prelims[offset % daily.prelims.length];
  const answers = ids.map((id) => prelims.questions.find((q) => q.id === id).answer), id = crypto.randomUUID();
  const attempt = { id, day, answers, score: -999 };
  const saved = await alice.json('/activity/practice', attempt); assert.equal(saved.status, 200); assert.equal(saved.body.score, ids.length * 2);
  assert.equal((await alice.json('/activity/practice', attempt)).body.id, id);
  assert.equal((await alice.json('/activity/practice', { ...attempt, answers: [null] })).status, 409);
  assert.equal((await alice.json('/activity/practice', { ...attempt, id: crypto.randomUUID(), day: '2026-02-31' })).status, 422);
  const receipt = { receiptId: crypto.randomUUID(), items: [{ kind: 'roadmap', value: { themeId: 1, completed: false, revision: 0 } }, { kind: 'maps', value: { id: crypto.randomUUID(), mapId: 'free-india', score: 3, seconds: 90 } }] };
  const imported = await alice.json('/activity/import', receipt); assert.equal(imported.body.imported, 1); assert.equal(imported.body.skipped, 1);
  assert.deepEqual((await alice.json('/activity/import', receipt)).body, imported.body);
  const snapshot = (await alice.json('/activity')).body;
  assert.equal(snapshot.roadmap[0].completed, true); assert.equal(snapshot.practice.length, 1); assert.equal(snapshot.maps.length, 1); assert.equal(snapshot.maps[0].selfReported, true);
  const exported = (await alice.json('/account/export')).body; assert.equal(exported.activities.practice.length, 1);
  assert.equal((await alice.json('/activity/maps', { id: crypto.randomUUID(), mapId: 'free-india', score: 999, seconds: 0 })).status, 422);
  const quiz = { id: crypto.randomUUID(), mode: 'quiz', mapId: 'india-states', score: 10, seconds: null };
  const quizSaved = await alice.json('/activity/maps', quiz);
  assert.equal(quizSaved.status, 200); assert.equal(quizSaved.body.selfReported, true); assert.equal(quizSaved.body.total, 10);
  assert.equal((await alice.json('/activity/maps', quiz)).status, 200);
  assert.equal((await alice.json('/activity/maps', { ...quiz, id: crypto.randomUUID(), score: 11 })).status, 422);
  assert.equal((await alice.json('/activity/maps', { ...quiz, id: crypto.randomUUID(), mapId: 'unknown-map' })).status, 422);
  await alice.json('/account/delete', { password: goodPassword });
  assert.equal((await bob.json('/activity')).body.maps.length, 0);
  assert.equal((await f.app.store.db.prepare('SELECT count(*) AS n FROM import_receipts').get()).n, 0);
});
